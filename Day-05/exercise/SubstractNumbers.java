class SubstractNum
{
	public static void main(String a [])
	{
		int s1 = Integer.parseInt(a [0]);
		int s2 = Integer.parseInt(a [1]);
		int result = s1-s2;
		
		System.out.println("First number is : " +s1);
		System.out.println("Second number is : " +s2);
		System.out.println("Substraction result is :" +result);
	}
}