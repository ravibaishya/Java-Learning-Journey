class AddTwoNumbers
{
	public static void main(String args[])
	{
		int f1 = Integer.parseInt(args[0]);
		int f2 = Integer.parseInt(args[1]);
		System.out.println("You have entered first number : " +f1);
		System.out.println("You have entered second number : " +f2);
		System.out.println("Sum of your two number is : " +(f1+f2));
	}
}