class RectArea
{
	public static void main(String ra[])
	{
		int l = Integer.parseInt(ra[0]);
		int b = Integer.parseInt(ra[1]);
		int ar = l * b ;
		System.out.println("Entered length is : "+l);
		System.out.println("Entered breadth is : "+b);
		System.out.println("Total area is : "+ar);
	}	
}