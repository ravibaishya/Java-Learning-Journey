class DivideNum
{
	public static void main(String d [])
	{
		int d1 = Integer.parseInt(d[0]);
		int d2 = Integer.parseInt(d[1]);
		int r = d1 / d2;
		
		System.out.println("First number : " +d1);
		System.out.println("Second number : " +d2);
		System.out.println("Division result :" +r);
	}
}